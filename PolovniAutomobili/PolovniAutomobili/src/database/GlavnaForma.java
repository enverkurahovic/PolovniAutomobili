    private void btnIzmeniActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIzmeniActionPerformed
        try {

    Connection con = DBConnection.getConnection();

    String naziv = txtNaziv.getText();

    String proizvodjac = cmbProizvodjac.getSelectedItem().toString();

    int proizvodjacID = 0;

    String sqlPro = "SELECT ProizvodjacID FROM proizvodjac WHERE Naziv=?";

    PreparedStatement pstPro = con.prepareStatement(sqlPro);

    pstPro.setString(1, proizvodjac);

    ResultSet rs = pstPro.executeQuery();

    if(rs.next()) {

        proizvodjacID = rs.getInt("ProizvodjacID");
    }

    String sql = "UPDATE model SET Naziv=?, ProizvodjacID=? " +
                 "WHERE ModelID=?";

    PreparedStatement pst = con.prepareStatement(sql);

    pst.setString(1, naziv);

    pst.setInt(2, proizvodjacID);

    pst.setInt(3, Integer.parseInt(txtSifra.getText()));

    int rezultat = pst.executeUpdate();

    if(rezultat > 0) {

        JOptionPane.showMessageDialog(this,
                "Uspešno izmenjeno!");

        ucitajModele();

    } else {

        JOptionPane.showMessageDialog(this,
                "Izmena nije uspela!");
    }

} catch(Exception e) {
    e.printStackTrace();
}
    }//GEN-LAST:event_btnIzmeniActionPerformed

