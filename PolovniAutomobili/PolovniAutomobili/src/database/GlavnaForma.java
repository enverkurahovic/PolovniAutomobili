  public void ucitajModele() {

    try {

        Connection con = DBConnection.getConnection();

        String sql = "SELECT model.ModelID, model.Naziv, proizvodjac.Naziv AS Proizvodjac " +
                     "FROM model INNER JOIN proizvodjac " +
                     "ON model.ProizvodjacID = proizvodjac.ProizvodjacID";

        PreparedStatement pst = con.prepareStatement(sql);

        ResultSet rs = pst.executeQuery();

        DefaultListModel model = new DefaultListModel();

        while(rs.next()) {

            String red = rs.getInt("ModelID") + "   "
                    + rs.getString("Naziv") + ", "
                    + rs.getString("Proizvodjac");

            model.addElement(red);
        }

        jListModeli.setModel(model);

    } catch(Exception e) {
        e.printStackTrace();
    }
}
  public void ucitajProizvodjace() {

    try {

        Connection con = DBConnection.getConnection();

        String sql = "SELECT * FROM proizvodjac";

        PreparedStatement pst = con.prepareStatement(sql);

        ResultSet rs = pst.executeQuery();

        cmbProizvodjac.removeAllItems();

        while(rs.next()) {

            cmbProizvodjac.addItem(rs.getString("Naziv"));
        }

    } catch(Exception e) {
        e.printStackTrace();
    }
}
  public void crtajGrafik() {

    Graphics g = panelGrafik.getGraphics();

    if(g == null) {
        return;
    }

    g.clearRect(0, 0,
            panelGrafik.getWidth(),
            panelGrafik.getHeight());

    int x = 30;

    for(int i = 0; i < brojevi.size(); i++) {

    int visina = brojevi.get(i) * 10;

    g.fillRect(x,
            250 - visina,
            40,
            visina);

    g.drawString(
            proizvodjaci.get(i),
            x,
            270
    );

    g.drawString(
            brojevi.get(i).toString(),
            x + 10,
            240 - visina
    );

    x += 70;
}
}
  
